#!/usr/bin/env node
/**
 * build-common-trips-manifest.js
 * -------------------------------
 * Writes common/data/trips-manifest.js -- window.TRIPS_MANIFEST, a flat
 * list of every travel-journal-YYYY-MM-DD/ trip folder plus its title,
 * straight out of that trip's own <trip>/trip-info.json (the same file
 * common/journal.html?trip=<folder> reads this manifest for -- see that
 * page's own top-of-script comment). travel-journals/index.html itself
 * reads this same manifest client-side for its own trip cards -- see
 * that page's own top-of-script comment -- rather than being generated
 * by a Node script the way it briefly was (build-travel-journal-
 * index.js, retired -- see scripts/_to_delete/build-travel-journal-
 * index_Instructions.txt).
 *
 * common/daily-location-gallery.html loads this file (a plain, static
 * <script src>, unconditional -- unlike the one trip-specific mirror it
 * ALSO loads based on ?trip=) to power two things: the trip picker shown
 * when no ?trip= is given, and the masthead "kicker" title once a trip
 * IS chosen (so that page doesn't need a second, hand-maintained copy of
 * each trip's display name). common/journal.html reads it the same way,
 * for its own <h1>/<title>.
 *
 * Usage:
 *   node scripts/javascript/build-common-trips-manifest.js
 *
 * No arguments, no npm dependencies (plain Node: fs + path only). Safe to
 * re-run any time -- always rescans fresh and overwrites
 * common/data/trips-manifest.js to match exactly what's on disk. Run it
 * whenever a travel-journal-YYYY-MM-DD folder is added, removed, or its
 * own trip-info.json's title changes -- travel-journals/index.html reads
 * this script's output live, so re-running this one is the only step
 * needed to keep that page (and common/daily-location-gallery.html's
 * trip picker) in sync; there is no longer a second generator to also
 * re-run.
 */

const fs = require("fs");
const path = require("path");

// This script lives at <travel-journals>/scripts/javascript/, so the
// collection root is two levels up.
const ROOT = path.resolve(__dirname, "..", "..");
const FOLDER_RE = /^travel-journal-(\d{4}-\d{2}-\d{2})$/;
const OUT_FILE = path.join(ROOT, "common", "data", "trips-manifest.js");

// A trip's subtitle line (date range, photo/video counts) used to be
// readable straight out of some trips' index.html -- for the others (the
// ones already rendering it client-side, id="journal-summary") it never
// was, and this script fell back to "" for those. Since August 2026,
// every trip's journal page is the client-side-rendered kind (common/
// journal.html?trip=<folder> -- see build-travel-journal-index_Instructions.txt
// and build-travel-journal_Instructions.txt's own retirement notes for
// the two-step history), so there is no longer any HTML file here to
// read a static subtitle out of at all -- sub is always "" now. The
// field stays in this manifest's shape (rather than being dropped)
// because common/daily-location-gallery.html's own code still reads it.
function collectTrips() {
  const entries = fs.readdirSync(ROOT, { withFileTypes: true });
  const trips = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const m = entry.name.match(FOLDER_RE);
    if (!m) continue;

    const infoPath = path.join(ROOT, entry.name, "trip-info.json");
    if (!fs.existsSync(infoPath)) continue; // trip folder exists but has no trip-info.json yet -- skip

    let info;
    try {
      info = JSON.parse(fs.readFileSync(infoPath, "utf8"));
    } catch (err) {
      console.warn(`Warning: couldn't parse ${infoPath} (${err.message}) -- skipping ${entry.name}.`);
      continue;
    }
    const title = (info && info.title) || entry.name;

    trips.push({ folder: entry.name, date: m[1], title, sub: "" });
  }

  // Chronological, oldest trip first -- same order and reasoning as
  // travel-journals/index.html's own trip cards (build-travel-journal-
  // index.js). Swap to (b, a) here for newest-first instead.
  trips.sort((a, b) => a.date.localeCompare(b.date));
  return trips;
}

function build() {
  const trips = collectTrips();
  const manifest = trips.map(({ folder, title, sub }) => ({ folder, title, sub }));

  const js =
    "// Generated by scripts/javascript/build-common-trips-manifest.js -- do not hand-edit.\n" +
    "// One entry per travel-journal-YYYY-MM-DD/ folder with its own trip-info.json, oldest first.\n" +
    "// Loaded by common/daily-location-gallery.html and common/journal.html to power\n" +
    "// their trip picker / per-trip title.\n" +
    "window.TRIPS_MANIFEST = " + JSON.stringify(manifest, null, 2) + ";\n";

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, js, "utf8");

  console.log(`Wrote ${OUT_FILE} with ${trips.length} trip${trips.length === 1 ? "" : "s"}:`);
  trips.forEach((t) => console.log(`  - ${t.folder}  "${t.title}"`));
}

build();
